def para_text(p):
    return "".join(
        node.text or ""
        for node in p.iter()
        if node.tag in {W + "t", M + "t"}
    )


def make_run(text: str):
    run = etree.Element(W + "r")
    rpr = etree.SubElement(run, W + "rPr")
    fonts = etree.SubElement(rpr, W + "rFonts")
    fonts.set(W + "ascii", "Times New Roman")
    fonts.set(W + "hAnsi", "Times New Roman")
    fonts.set(W + "eastAsia", "宋体")
    etree.SubElement(rpr, W + "b").set(W + "val", "0")
    etree.SubElement(rpr, W + "sz").set(W + "val", "24")
    text_node = etree.SubElement(run, W + "t")
    if text.startswith(" ") or text.endswith(" "):
        text_node.set(XML_SPACE, "preserve")
    text_node.text = text
    return run


def set_mixed(p, parts, transform):
    ppr = p.find("w:pPr", namespaces=NS)
    for child in list(p):
        if child is not ppr:
            p.remove(child)
    for part in parts:
        if isinstance(part, tuple):
            kind, value = part
            if kind != "math":
                raise ValueError(f"unknown part kind: {kind}")
            p.append(latex_to_omml(value, transform))
        elif part:
            p.append(make_run(part))


def set_text(p, text: str, transform):
    set_mixed(p, [text], transform)


def find_one(paras, *, exact=None, starts=None):
    matches = []
    for p in paras:
        text = para_text(p)
        if exact is not None and text == exact:
            matches.append(p)
        elif starts is not None and text.startswith(starts):
            matches.append(p)
    if len(matches) != 1:
        mode = f"exact={exact!r}" if exact is not None else f"starts={starts!r}"
        raise RuntimeError(f"expected one paragraph for {mode}, found {len(matches)}")
    return matches[0]


def replace_exact(paras, old, new, transform):
    set_text(find_one(paras, exact=old), new, transform)


def replace_start(paras, prefix, parts, transform):
    set_mixed(find_one(paras, starts=prefix), parts, transform)


