def add_description_numbers(body):
    headings = {"技术领域", "背景技术", "发明内容", "附图说明", "具体实施方式"}
    active = False
    number = 1
    for p in body.findall("w:p", namespaces=NS):
        text = para_text(p)
        if text == "技术领域":
            active = True
            continue
        if text == "图1":
            break
        if not active or not text or text in headings:
            continue
        prefix = make_run(f"[{number:04d}] ")
        ppr = p.find("w:pPr", namespaces=NS)
        insert_at = 1 if ppr is not None and len(p) and p[0] is ppr else 0
        p.insert(insert_at, prefix)
        number += 1
    return number - 1


def set_page_margins(root):
    sect_pr = root.find(".//w:body/w:sectPr", namespaces=NS)
    if sect_pr is None:
        raise RuntimeError("missing sectPr")
    pg_mar = sect_pr.find("w:pgMar", namespaces=NS)
    if pg_mar is None:
        pg_mar = etree.SubElement(sect_pr, W + "pgMar")
    pg_mar.set(W + "top", "1417")
    pg_mar.set(W + "left", "1417")
    pg_mar.set(W + "bottom", "850")
    pg_mar.set(W + "right", "850")


def patch():
    backup = TARGET.with_name(
        TARGET.stem + f"_全文专利化修改前备份_{time.strftime('%Y%m%d_%H%M%S')}.docx"
    )
    shutil.copy2(TARGET, backup)
    tmp = TARGET.with_suffix(".tmp.docx")

    transform = build_transform()
    with ZipFile(TARGET, "r") as zin:
        root = etree.fromstring(zin.read("word/document.xml"))
        body = root.find("w:body", namespaces=NS)
        paras = body.findall("w:p", namespaces=NS)

        # Abstract follows the centered heading.
        abstract_heading = find_one(paras, exact="摘要")
        abstract_index = paras.index(abstract_heading)
        set_text(paras[abstract_index + 1], ABSTRACT, transform)

        patch_claims(paras, transform)
        patch_description(paras, transform)
        numbered = add_description_numbers(body)
        set_page_margins(root)

        if len(ABSTRACT) > 300:
            raise RuntimeError(f"abstract exceeds 300 characters: {len(ABSTRACT)}")

        new_xml = etree.tostring(
            root, xml_declaration=True, encoding="UTF-8", standalone="yes"
        )
        with ZipFile(tmp, "w", ZIP_DEFLATED) as zout:
            for info in zin.infolist():
                data = zin.read(info.filename)
                if info.filename == "word/document.xml":
                    data = new_xml
                zout.writestr(info, data)

    tmp.replace(TARGET)
    return backup, numbered


if __name__ == "__main__":
    backup_path, paragraph_count = patch()
    print(f"target={TARGET}")
    print(f"backup={backup_path}")
